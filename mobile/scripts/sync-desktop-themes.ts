/**
 * Generate the curated four-theme mobile catalog.
 *
 * - Gruvbox Dark / Gruvbox Light are canonical desktop data: parsed at build
 *   time from `dragent/crates/dragent_viewer/assets/themes/standard/*.yaml`
 *   with the `yaml` package. Never hand-copy those palettes.
 * - Neutral Dark / Light are mobile-authored (`NEUTRAL_*_THEME` in
 *   `src/theme/derive.ts`) and imported as-is.
 *
 * Run from `mobile/`:
 *   pnpm tsx scripts/sync-desktop-themes.ts            # regenerate
 *   pnpm tsx scripts/sync-desktop-themes.ts --check    # fail on drift (CI)
 *
 * The mobile runtime never reads desktop files. Malformed desktop palettes
 * fail with the file path + reason.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import {
  CURATED_THEME_IDS,
  DARK_THEME_ID,
  LIGHT_THEME_ID,
  NEUTRAL_DARK_THEME,
  NEUTRAL_LIGHT_THEME,
  displayNameForId,
  parseDesktopYaml,
  toAppTheme,
} from "../src/theme/derive";
import type { AppTheme } from "../src/theme/types";

const HERE = fileURLToPath(new URL(".", import.meta.url));
const MOBILE_DIR = join(HERE, "..");
const REPO_ROOT = join(MOBILE_DIR, "..");
const DESKTOP_THEMES_DIR = join(REPO_ROOT, "dragent", "crates", "dragent_viewer", "assets", "themes", "standard");
const OUTPUT_FILE = join(MOBILE_DIR, "src", "theme", "catalog.generated.ts");

/** The only desktop files the mobile catalog may draw from. */
const GRUVBOX_SOURCES = [
  { file: "gruvbox_dark.yaml", id: "gruvbox_dark", mode: "dark" as const },
  { file: "gruvbox_light.yaml", id: "gruvbox_light", mode: "light" as const },
];

/** Parse the canonical desktop Gruvbox pair and derive their app themes. */
export function loadGruvboxThemes(themesDir: string = DESKTOP_THEMES_DIR): AppTheme[] {
  return GRUVBOX_SOURCES.map(({ file, id, mode }) => {
    const full = join(themesDir, file);
    const rel = relative(REPO_ROOT, full);
    let raw: string;
    try {
      raw = readFileSync(full, "utf8");
    } catch (error) {
      throw new Error(`${rel}: cannot read file (${error instanceof Error ? error.message : String(error)})`);
    }
    let theme: AppTheme;
    try {
      theme = toAppTheme(parseDesktopYaml(raw, { id, name: displayNameForId(id) }));
    } catch (error) {
      const reason = error instanceof Error ? error.message : String(error);
      throw new Error(`${rel}: ${reason}`);
    }
    if (theme.mode !== mode) {
      throw new Error(`${rel}: expected a ${mode} theme, parsed "${theme.mode}"`);
    }
    return theme;
  });
}

/** The curated catalog in display order: neutral Dark, Gruvbox pair, neutral Light. */
export function loadCuratedThemes(themesDir: string = DESKTOP_THEMES_DIR): AppTheme[] {
  const gruvbox = loadGruvboxThemes(themesDir);
  const byId = new Map(gruvbox.map((entry) => [entry.id, entry]));
  const ordered: AppTheme[] = [NEUTRAL_DARK_THEME];
  for (const source of GRUVBOX_SOURCES) {
    const theme = byId.get(source.id);
    if (!theme) throw new Error(`Curated catalog is missing "${source.id}"`);
    ordered.push(theme);
  }
  ordered.push(NEUTRAL_LIGHT_THEME);
  const ids = ordered.map((entry) => entry.id);
  if (ids.length !== CURATED_THEME_IDS.length || !CURATED_THEME_IDS.every((id, index) => ids[index] === id)) {
    throw new Error(`Curated catalog must be exactly [${CURATED_THEME_IDS.join(", ")}], got [${ids.join(", ")}]`);
  }
  if (ordered[0]!.id !== DARK_THEME_ID || ordered[ordered.length - 1]!.id !== LIGHT_THEME_ID) {
    throw new Error(`Curated catalog must start with "${DARK_THEME_ID}" and end with "${LIGHT_THEME_ID}"`);
  }
  return ordered;
}

function quote(value: string): string {
  return JSON.stringify(value);
}

function renderStringArray(values: readonly string[]): string {
  return `[${values.map(quote).join(", ")}]`;
}

export function renderCatalog(themes: readonly AppTheme[]): string {
  const lines: string[] = [
    `// DO NOT EDIT — generated by scripts/sync-desktop-themes.ts from`,
    `// - neutral Dark/Light (mobile-authored in src/theme/derive.ts)`,
    `// - Gruvbox Dark/Light parsed from dragent/crates/dragent_viewer/assets/themes/standard/*.yaml.`,
    `// Run \`tsx scripts/sync-desktop-themes.ts\` to regenerate.`,
    `import type { AppTheme } from "./types";`,
    ``,
    `/** The curated four-theme catalog served to the UI. */`,
    `export const BUNDLED_THEMES: readonly AppTheme[] = [`,
  ];
  for (const theme of themes) {
    lines.push(`  {`);
    lines.push(`    id: ${quote(theme.id)},`);
    lines.push(`    name: ${quote(theme.name)},`);
    lines.push(`    mode: ${quote(theme.mode)},`);
    lines.push(`    colors: {`);
    for (const [key, value] of Object.entries(theme.colors)) {
      lines.push(`      ${key}: ${quote(value)},`);
    }
    lines.push(`    },`);
    lines.push(`    terminal: {`);
    lines.push(`      background: ${quote(theme.terminal.background)},`);
    lines.push(`      foreground: ${quote(theme.terminal.foreground)},`);
    lines.push(`      cursor: ${quote(theme.terminal.cursor)},`);
    lines.push(`      ansiNormal: ${renderStringArray(theme.terminal.ansiNormal)},`);
    lines.push(`      ansiBright: ${renderStringArray(theme.terminal.ansiBright)},`);
    lines.push(`    },`);
    lines.push(`  },`);
  }
  lines.push(`];`);
  lines.push(``);
  return lines.join("\n");
}

function main(): void {
  const check = process.argv.includes("--check");
  const themes = loadCuratedThemes();
  const rendered = renderCatalog(themes);
  if (check) {
    let current: string;
    try {
      current = readFileSync(OUTPUT_FILE, "utf8");
    } catch {
      console.error(`Theme catalog missing: run \`tsx scripts/sync-desktop-themes.ts\` to generate it.`);
      process.exit(1);
    }
    if (current !== rendered) {
      console.error(
        `Theme catalog drift: ${relative(REPO_ROOT, OUTPUT_FILE)} differs from the curated source.\n` +
          `Run \`tsx scripts/sync-desktop-themes.ts\` from mobile/ to regenerate.`,
      );
      process.exit(1);
    }
    console.log(`Theme catalog in sync (${themes.length} themes: ${themes.map((entry) => entry.id).join(", ")}).`);
    return;
  }
  writeFileSync(OUTPUT_FILE, rendered, "utf8");
  console.log(`Wrote ${relative(REPO_ROOT, OUTPUT_FILE)} (${themes.length} themes).`);
}

if (require.main === module) {
  try {
    main();
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exit(1);
  }
}
