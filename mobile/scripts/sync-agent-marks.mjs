// Brings each desktop agent's icon to the phone, as the desktop draws it
// (`PromptAgent::image_path` in dragent/app/src/workspace/action.rs). Keyed by
// the agent's command name, which is what the desktop's catalog sends as a
// tab's agent. SVGs are embedded as text; PNGs are copied (shrunk to 128 px).
// The seven hand-drawn marks in AgentMark.tsx stay as they are.
//
// Run from mobile/: node scripts/sync-agent-marks.mjs
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, copyFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const mobile = path.resolve(here, "..");
const images = path.resolve(mobile, "../dragent/app/assets/dragent/agent-images");

import { AGENTS } from "./agent-marks-table.mjs";

function source(file) {
  const full = path.join(images, file);
  if (!existsSync(full)) throw new Error(`missing desktop icon ${full}`);
  if (file.endsWith(".svg")) {
    return { kind: "svg", text: readFileSync(full, "utf8").replace(/<\?xml[^>]*>\s*/g, "").trim() };
  }
  const name = path.basename(file).toLowerCase();
  const target = path.join(mobile, "assets/agents/marks", name);
  copyFileSync(full, target);
  // Never keep more pixels than the phone draws (a few dozen points); small
  // icons stay as they are.
  const width = Number(/pixelWidth: (\d+)/.exec(execFileSync("sips", ["-g", "pixelWidth", target], { encoding: "utf8" }))?.[1]);
  if (width > 128) execFileSync("sips", ["-Z", "128", target], { stdio: "ignore" });
  return { kind: "png", name };
}

const lines = [
  "// Generated by scripts/sync-agent-marks.mjs from the desktop's agent icons.",
  "// Don't edit by hand: change the script's table and run it again.",
  "/* eslint-disable */",
  "",
  "export type AgentMarkArt =",
  "  | { readonly kind: \"svg\"; readonly svg: string }",
  "  | { readonly kind: \"png\"; readonly png: number };",
  "",
  "export interface AgentMarkEntry {",
  "  readonly label: string;",
  "  readonly light: AgentMarkArt;",
  "  readonly dark: AgentMarkArt | null;",
  "}",
  "",
  "export const AGENT_MARKS: Readonly<Record<string, AgentMarkEntry>> = Object.freeze({",
];
const render = (art) =>
  art.kind === "svg"
    ? `{ kind: "svg", svg: ${JSON.stringify(art.text)} }`
    : `{ kind: "png", png: require("../../assets/agents/marks/${art.name}") }`;
for (const [id, label, light, dark] of AGENTS) {
  lines.push(
    `  ${JSON.stringify(id)}: { label: ${JSON.stringify(label)}, light: ${render(source(light))}, dark: ${dark ? render(source(dark)) : "null"} },`,
  );
}
lines.push("});", "");
writeFileSync(path.join(mobile, "src/components/agentMarks.generated.ts"), lines.join("\n"));
console.log(`wrote ${AGENTS.length} agent marks`);
