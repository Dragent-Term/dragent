//! §8 push fixtures for the device-side tests (E9a). Every blob is a real
//! Noise X seal of a real 1,024-byte plaintext; the expected outcome says
//! what the extension / messaging service must show.
use dragent_e2ee::codec::{b64, push_plain::PushPlain};
use dragent_e2ee::noise::{PushPrologue, StaticKeypair};
use dragent_e2ee::seal::push as seal;
use dragent_e2ee::zeroize::Zeroizing;
use dragent_e2ee::Id;
use serde_json::{json, Value};
use sha2::{Digest, Sha256};

const NOW: u64 = 1_800_000_000_000;
const HOUR: u64 = 60 * 60 * 1000;

fn key(b: u8) -> StaticKeypair {
    StaticKeypair::from_secret_bytes(&Zeroizing::new([b; 32]))
}
fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}
fn id(s: &str) -> Id {
    Id::parse(s).unwrap()
}

fn main() {
    let account = id("0a0b0c0d-0000-4000-8000-0000000000aa");
    let phone = id("0a0b0c0d-0000-4000-8000-0000000000a1");
    let other_phone = id("0a0b0c0d-0000-4000-8000-0000000000a2");
    let desk_a = id("0a0b0c0d-0000-4000-8000-0000000000d1");
    let desk_b = id("0a0b0c0d-0000-4000-8000-0000000000d2");
    let workspace = id("0a0b0c0d-0000-4000-8000-0000000000e1");
    let nil = Id([0; 16]);
    let (a, b) = (key(0xA1), key(0xB2));
    let (push, previous) = (key(0x51), key(0x50));

    let pro = |p: Id, acc: Id| PushPrologue { account: acc, phone: p };
    let show = |n: u8, title: &str, body: &str, desk: Id, ws: Id, at: u64| {
        PushPlain::notification(desk, [n; 16], at, 2, title, body, ws, nil).unwrap()
    };
    let sealed = |from: &StaticKeypair, to: &StaticKeypair, pr: PushPrologue, p: &PushPlain| {
        b64::encode(&seal::seal(from, &to.public(), &pr, &p.encode().unwrap()).unwrap())
    };
    let thread = |desk: Id, ws: Id| {
        let mut h = Sha256::new();
        h.update(desk.as_bytes());
        h.update(ws.as_bytes());
        hex(&h.finalize())
    };
    let ok = |blob: String, p: &PushPlain| {
        json!({"blob": blob, "expect": "show", "title": p.title, "body": p.body,
               "id": hex(&p.id), "thread": thread(p.desktop_id, p.workspace_id), "desktop": p.desktop_id.to_string()})
    };
    let fail = |blob: String, why: &str| json!({"blob": blob, "expect": "placeholder", "why": why});

    let valid = show(1, "Build finished ✓", "All 12 tests passed", desk_a, workspace, NOW - 1000);
    let max = show(2, &"t".repeat(240), &"b".repeat(600), desk_a, nil, NOW);
    let mut cases = serde_json::Map::new();
    cases.insert("valid".into(), ok(sealed(&a, &push, pro(phone, account), &valid), &valid));
    cases.insert("max_length".into(), ok(sealed(&a, &push, pro(phone, account), &max), &max));
    let prev = show(3, "Older key", "Sealed before rotation", desk_a, nil, NOW - HOUR);
    cases.insert("previous_push_key".into(), ok(sealed(&a, &previous, pro(phone, account), &prev), &prev));
    let unpinned = show(4, "Unpinned", "x", desk_a, nil, NOW);
    cases.insert("unpinned_sender".into(), fail(sealed(&b, &push, pro(phone, account), &unpinned), "sender key not in the push-pin list"));
    let mismatch = show(5, "Mismatch", "x", desk_b, nil, NOW);
    cases.insert("desktop_id_mismatch".into(), fail(sealed(&a, &push, pro(phone, account), &mismatch), "pinned desktop differs from inner desktop_id"));
    let stale = show(6, "Stale", "x", desk_a, nil, NOW - 25 * HOUR);
    cases.insert("stale".into(), fail(sealed(&a, &push, pro(phone, account), &stale), "older than 24 hours"));
    let dismiss = PushPlain::dismissal(desk_a, [7; 16], NOW, 0, nil, nil, vec![[1; 16]]).unwrap();
    cases.insert("dismissal".into(), json!({"blob": sealed(&a, &push, pro(phone, account), &dismiss), "expect": "dismiss", "dismiss_ids": [hex(&[1; 16])]}));
    let w = show(8, "Wrong phone", "x", desk_a, nil, NOW);
    cases.insert("wrong_phone".into(), fail(sealed(&a, &push, pro(other_phone, account), &w), "prologue names another phone"));
    let mut tampered = b64::decode(cases["valid"]["blob"].as_str().unwrap()).unwrap();
    tampered[600] ^= 1;
    cases.insert("tampered".into(), fail(b64::encode(&tampered), "bad tag"));
    cases.insert("truncated".into(), fail(cases["valid"]["blob"].as_str().unwrap()[..1490].to_string(), "wrong length"));
    cases.insert("not_base64".into(), fail("!".repeat(1494), "not base64url"));

    let out: Value = json!({
        "comment": "Generated by plugins/e2ee-nse/fixtures/gen (real dragent_e2ee seals). Do not edit.",
        "now_ms": NOW,
        "account": account.to_string(),
        "phone": phone.to_string(),
        "push_secret": hex(&push.secret_bytes()[..]),
        "previous_push_secret": hex(&previous.secret_bytes()[..]),
        "previous_retired_at_ms": NOW - 24 * HOUR,
        "pins": [{"desktop": desk_a.to_string(), "key": hex(a.public().as_bytes())}],
        "placeholder": {"title": "Dragent", "body": "An agent needs you"},
        "cases": cases,
    });
    println!("{}", serde_json::to_string_pretty(&out).unwrap());
}
