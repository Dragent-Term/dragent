//! `Noise_IKpsk1_25519_ChaChaPoly_SHA256`: pairing (§6.2).
//!
//! ```text
//! IKpsk1:  <- s                    (pre-message: desktop key from the QR `k`)
//!          ...
//!          -> e, es, s, ss, psk     HS1  payload {device_name, platform, push_pub}
//!          <- e, ee, se             HS2  empty payload
//! ```
//!
//! The PSK is mixed at the end of HS1, so the desktop authenticates possession
//! of the QR secret `P` from HS1 on. The phone then confirms with DATA ctr 0 =
//! CTRL `pair-confirm {h}`, `h` being [`Transport::handshake_hash`]; the desktop
//! compares it with [`confirm_hash_matches`] before pinning anything.

use hkdf::Hkdf;
use sha2::Sha256;
use zeroize::Zeroizing;

use super::{
    ct_eq, hs_read, hs_write, NoiseError, PairingPrologue, PublicKey, Setup, StaticKeypair,
    Transport, IKPSK1,
};
use crate::ids::Id;
use crate::rng::{fill_random, RandomError};

/// HKDF `info` for the pairing PSK (§6.2 step 5).
pub const PSK_INFO: &[u8] = b"dragent pairing psk v1";

/// The QR secret `P`: 32 random bytes generated by the desktop, held in memory
/// only (10 minutes on the desktop; wiped on the phone when pairing ends).
pub struct PairingSecret(Zeroizing<[u8; 32]>);

impl PairingSecret {
    /// A fresh `P`.
    pub fn generate() -> Result<Self, RandomError> {
        let mut p = Zeroizing::new([0u8; 32]);
        fill_random(&mut p[..])?;
        Ok(PairingSecret(p))
    }

    /// `P` as decoded from the QR or link.
    pub fn from_bytes(bytes: Zeroizing<[u8; 32]>) -> Self {
        PairingSecret(bytes)
    }

    /// The raw bytes, for encoding into the QR only.
    pub fn as_bytes(&self) -> &[u8; 32] {
        &self.0
    }

    /// `psk = HKDF-SHA256(ikm = P, salt = desktop_id, info = "dragent pairing psk v1")`.
    ///
    /// `salt` is the desktop id in its canonical lowercase text form (the `d`
    /// value of the pairing link, and the same spelling as the §5 prologues).
    pub fn psk(&self, desktop: &Id) -> PairingPsk {
        let salt = desktop.to_string();
        let hk = Hkdf::<Sha256>::new(Some(salt.as_bytes()), &self.0[..]);
        let mut okm = Zeroizing::new([0u8; 32]);
        hk.expand(PSK_INFO, &mut okm[..])
            .expect("32 bytes is a valid HKDF-SHA256 length");
        PairingPsk(okm)
    }
}

/// The derived pairing PSK.
pub struct PairingPsk(Zeroizing<[u8; 32]>);

impl PairingPsk {
    #[cfg(test)]
    pub(crate) fn bytes(&self) -> &[u8; 32] {
        &self.0
    }
}

/// The phone after sending pairing HS1.
pub struct PairingInitiator {
    hs: snow::HandshakeState,
}

impl PairingInitiator {
    /// Build HS1 to the desktop key taken **from the QR** (never from the
    /// server's redeem response).
    pub fn start(
        local: &StaticKeypair,
        desktop_key_from_qr: &PublicKey,
        psk: &PairingPsk,
        prologue: &PairingPrologue,
        payload: &[u8],
    ) -> Result<(Self, Vec<u8>), NoiseError> {
        let p = prologue.bytes();
        let mut setup = Setup::new(IKPSK1, &p);
        setup.local_secret = Some(local.secret_slice());
        setup.remote_public = Some(desktop_key_from_qr.as_bytes());
        setup.psk = Some((1, &psk.0));
        let mut hs = setup.build(true)?;
        let hs1 = hs_write(&mut hs, payload)?;
        Ok((PairingInitiator { hs }, hs1))
    }

    /// Process HS2 (empty payload). The phone then sends `pair-confirm {h}`
    /// with `h = transport.handshake_hash()`.
    pub fn read_hs2(mut self, hs2: &[u8]) -> Result<Transport, NoiseError> {
        let payload = hs_read(&mut self.hs, hs2)?;
        if !payload.is_empty() {
            return Err(NoiseError::Malformed);
        }
        Transport::from_handshake(self.hs)
    }
}

/// The desktop after a valid pairing HS1: a tentative record, nothing pinned.
pub struct PairingResponder {
    hs: snow::HandshakeState,
    phone_static: PublicKey,
}

impl PairingResponder {
    /// Process HS1. Success proves knowledge of `P` and possession of the
    /// phone's static key, which is returned with the payload. Pin nothing and
    /// don't consume `P` yet (§6.2 step 6).
    pub fn read_hs1(
        local: &StaticKeypair,
        psk: &PairingPsk,
        prologue: &PairingPrologue,
        hs1: &[u8],
    ) -> Result<(Self, PublicKey, Zeroizing<Vec<u8>>), NoiseError> {
        let p = prologue.bytes();
        let mut setup = Setup::new(IKPSK1, &p);
        setup.local_secret = Some(local.secret_slice());
        setup.psk = Some((1, &psk.0));
        let mut hs = setup.build(false)?;
        let payload = hs_read(&mut hs, hs1)?;
        let phone_static = hs
            .get_remote_static()
            .and_then(PublicKey::from_slice)
            .ok_or(NoiseError::Internal)?;
        Ok((PairingResponder { hs, phone_static }, phone_static, payload))
    }

    /// The phone's static key learned from HS1.
    pub fn phone_static(&self) -> PublicKey {
        self.phone_static
    }

    /// Build HS2 with an empty payload.
    pub fn write_hs2(mut self) -> Result<(Transport, Vec<u8>), NoiseError> {
        let hs2 = hs_write(&mut self.hs, &[])?;
        Ok((Transport::from_handshake(self.hs)?, hs2))
    }
}

/// Whether the `h` in the phone's `pair-confirm {h}` equals our handshake hash
/// (constant time).
pub fn confirm_hash_matches(transport: &Transport, h: &[u8]) -> bool {
    ct_eq(transport.handshake_hash(), h)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ids::ChannelId;

    fn prologue() -> PairingPrologue {
        PairingPrologue {
            account: Id([1; 16]),
            phone: Id([2; 16]),
            desktop: Id([3; 16]),
            chan: ChannelId([4; 16]),
        }
    }

    #[test]
    fn psk_derivation_vector() {
        // HKDF-SHA256(ikm = 0x00..1f, salt = "03030303-0303-0303-0303-030303030303",
        // info = "dragent pairing psk v1"), computed independently with Python
        // hmac/hashlib. Pinned so the phone module can
        // check it derives the same value.
        let mut p = Zeroizing::new([0u8; 32]);
        for (i, b) in p.iter_mut().enumerate() {
            *b = i as u8;
        }
        let psk = PairingSecret::from_bytes(p).psk(&Id([3; 16]));
        assert_eq!(
            crate::ids::hex_lower(psk.bytes()),
            "209f53ead368968b5f72cbf7d635f0622bad6e6a2faa07c1d459cddf0c5e968f"
        );
    }

    #[test]
    fn pairing_round_trip_and_confirm() {
        let phone = StaticKeypair::generate().unwrap();
        let desktop = StaticKeypair::generate().unwrap();
        let p = PairingSecret::generate().unwrap();
        let psk = p.psk(&Id([3; 16]));
        let (init, hs1) =
            PairingInitiator::start(&phone, &desktop.public(), &psk, &prologue(), b"{}").unwrap();
        let (resp, phone_key, payload) =
            PairingResponder::read_hs1(&desktop, &psk, &prologue(), &hs1).unwrap();
        assert_eq!(phone_key, phone.public());
        assert_eq!(&payload[..], b"{}");
        let (dt, hs2) = resp.write_hs2().unwrap();
        let pt = init.read_hs2(&hs2).unwrap();
        assert!(confirm_hash_matches(&dt, pt.handshake_hash()));
        assert!(!confirm_hash_matches(&dt, &[0u8; 32]));
    }

    #[test]
    fn hs1_without_p_is_rejected() {
        // §12.5: HS1 with the relay's own key and no P gives nothing.
        let relay = StaticKeypair::generate().unwrap();
        let desktop = StaticKeypair::generate().unwrap();
        let real = PairingSecret::generate().unwrap().psk(&Id([3; 16]));
        let guess = PairingSecret::generate().unwrap().psk(&Id([3; 16]));
        let (_, hs1) =
            PairingInitiator::start(&relay, &desktop.public(), &guess, &prologue(), b"").unwrap();
        assert!(PairingResponder::read_hs1(&desktop, &real, &prologue(), &hs1).is_err());
    }

    #[test]
    fn substituted_desktop_key_is_caught() {
        // The phone uses the QR's key; a relay that answered with its own key
        // in the redeem response can't complete the handshake as the desktop.
        let phone = StaticKeypair::generate().unwrap();
        let desktop = StaticKeypair::generate().unwrap();
        let relay = StaticKeypair::generate().unwrap();
        let psk = PairingSecret::generate().unwrap().psk(&Id([3; 16]));
        let (_, hs1) =
            PairingInitiator::start(&phone, &desktop.public(), &psk, &prologue(), b"").unwrap();
        assert!(PairingResponder::read_hs1(&relay, &psk, &prologue(), &hs1).is_err());
    }

    #[test]
    fn psk_is_bound_to_desktop_id() {
        let p = PairingSecret::generate().unwrap();
        assert_ne!(p.psk(&Id([3; 16])).bytes(), p.psk(&Id([4; 16])).bytes());
    }
}
