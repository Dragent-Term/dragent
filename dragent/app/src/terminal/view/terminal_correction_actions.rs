impl TerminalView {
    pub(crate) fn handle_terminal_correction_action(
        &mut self,
        action: &TerminalAction,
        ctx: &mut ViewContext<Self>,
    ) {
        match action {
            TerminalAction::DismissConfirm => {
                self.pending_confirm = None;
                ctx.notify();
                self.poke_workspace_confirm(ctx);
            }
            TerminalAction::ResolveConfirm { confirm, action } => {
                self.pending_confirm = None;
                if *confirm {
                    let a = (**action).clone();
                    self.handle_action(&a, ctx);
                }
                ctx.notify();
                self.poke_workspace_confirm(ctx);
            }
            _ => {}
        }
    }
}
