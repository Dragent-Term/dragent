impl TerminalView {
    /// Pending destructive-action confirm, cloned for the window-level
    /// mirror in WorkspaceView. The terminal still owns and clears it; the
    /// mirror shows whenever the pane is not actually visible (background
    /// tab, or active tab covered by the document center), so the two never
    /// double-render.
    pub fn pending_confirm_request(&self) -> Option<crate::confirm::ConfirmRequest> {
        self.pending_confirm.clone()
    }

    /// Dirty the hosting workspace view so its window-level confirm mirror
    /// renders in the same frame as this change. View dirtiness is
    /// per-view: notifying only self would leave the mirror a full
    /// workspace render cycle (~1s) behind the click. Dispatched from self,
    /// the action climbs the responder chain to the workspace ancestor.
    /// Deferred: dispatching synchronously from inside this view's own
    /// action handler re-enters the checked-out view and panics
    /// ("circular view reference").
    pub(crate) fn poke_workspace_confirm(&self, ctx: &mut ViewContext<Self>) {
        ctx.dispatch_typed_action_deferred(
            crate::workspace::WorkspaceAction::TerminalConfirmChanged,
        );
    }

    /// In-pane confirms are intentionally disabled: every pending
    /// destructive-action and quit-guard modal renders exactly once at
    /// window level (WorkspaceView's terminal-confirm mirror), topmost over
    /// any screen. Rendering here too produced stacked doubles with a
    /// visible lag between the two layers.
    pub(crate) fn overlay_confirm_modals(
        &self,
        root: Box<dyn Element>,
        _theme: Theme,
    ) -> Box<dyn Element> {
        root
    }

    pub(crate) fn show_error_notice(&mut self, error: (String, String), ctx: &mut ViewContext<Self>) {
        self.error_toast = None;
        ctx.dispatch_typed_action_deferred(crate::workspace::WorkspaceAction::ShowErrorNotice { title: error.0, message: error.1 });
    }

    pub(crate) fn render_error_toast(&self, title: &str, error: &str, theme: &crate::theme::Theme) -> Box<dyn Element> {
        crate::error_notice::render(title, error, theme, self.mono_family,
            self.branch_diff_error_scroll.clone(), self.commit_error_copied, self.pane_view_id,
            TerminalAction::DismissCommitError, TerminalAction::CopyCommitError { text: error.to_string() })
    }
}
