impl WorkspaceView {
    pub(crate) fn handle_terminal_action(
        &mut self,
        action: &WorkspaceAction,
        ctx: &mut ViewContext<Self>,
    ) {
        match action {
            WorkspaceAction::NewWindow => {
                // ViewContext derefs to AppContext, so we can open a top-level window
                // from here. New windows start empty (see RootView::new_empty).
                #[cfg(not(target_family = "wasm"))]
                crate::desktop::open_new_window(ctx);
            }
            // Caption buttons of the custom Windows titlebar. CloseWindow goes
            // through the same cancellable path as the OS close request, so the
            // last-window teardown in `on_window_will_close` still runs.
            WorkspaceAction::MinimizeWindow => ctx.minimize_window(),
            WorkspaceAction::ToggleMaximizeWindow => ctx.toggle_maximized_window(),
            WorkspaceAction::CloseWindow => ctx.close_window(),
            WorkspaceAction::RunActivePaneCommand { command } => {
                if self.pull_requests_open || self.settings_open || self.automations_open || self.teams_open || self.tasks_open || self.project_start_visible {
                    let root = self.active_project_root();
                    self.open_page_command_terminal("Run command", root, command, ctx);
                    return;
                }
                if command.trim().is_empty() {
                    return;
                }
                // Project commands get their own PTY. Sending one into the
                // active pane can hand it to an agent REPL or hide its session.
                let response = self.pane_tool_for_cli(
                    None,
                    None,
                    "open",
                    &serde_json::json!({
                        "target": self.active_tab_id,
                        "command": command,
                        "label": "Run command",
                    }),
                    ctx,
                );
                if !response.ok {
                    self.show_error_notice(
                        "Input failed",
                        response.error.unwrap_or_else(|| "Could not open a command pane.".into()),
                        ctx,
                    );
                }
            }
            _ => {}
        }
    }
}
